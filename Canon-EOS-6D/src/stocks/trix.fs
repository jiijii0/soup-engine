# Kodak Tri-X 400: black and white with real grit.
#
# Acros is the smooth one: fine grain, a long clean tonal scale, a hard
# shoulder. Tri-X is the opposite temperament. The grain is big and shows
# everywhere, the contrast is firm, blacks go to ink, and the midtones are
# a little heavier. It is the photojournalism film, and it earns that by
# looking like it was shot in a hurry in bad light.
#
# SAT 0 makes it monochrome; the three channel curves then act as the
# colour filter on the lens. Tri-X is a plain panchromatic film, so the
# filter is mild -- a touch of red up and blue down, which lightens skin
# and darkens sky slightly without going to a full red filter.
#
# Against ACROS: that is GRAIN 20 and a size-16 cell. This is 54 and 32.
