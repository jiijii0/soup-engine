#!/usr/bin/env python3
"""
Generate engine/ui_font.c from ASCII art.

The camera's overlay is 720x240 at 4 bits per pixel, so the UI needs its
own small font rather than Magic Lantern's. Authoring the glyphs as art
keeps them reviewable; the hex table below is generated, never hand-typed.

Each glyph is 5 wide and 7 tall, stored as 5 column bytes, bit 0 = top row.
"""
import sys

G = {}

def g(ch, *rows):
    assert len(rows) == 7, ch
    for r in rows:
        assert len(r) == 5, (ch, r)
    G[ch] = rows

g(' ', '.....','.....','.....','.....','.....','.....','.....')
g('!', '..#..','..#..','..#..','..#..','..#..','.....','..#..')
g('(', '...#.','..#..','.#...','.#...','.#...','..#..','...#.')
g(')', '.#...','..#..','...#.','...#.','...#.','..#..','.#...')
g('+', '.....','..#..','..#..','#####','..#..','..#..','.....')
g(',', '.....','.....','.....','.....','.##..','.##..','.#...')
g('-', '.....','.....','.....','#####','.....','.....','.....')
g('.', '.....','.....','.....','.....','.....','.##..','.##..')
g('/', '....#','...#.','...#.','..#..','.#...','.#...','#....')
g(':', '.....','.##..','.##..','.....','.##..','.##..','.....')
g('<', '...#.','..#..','.#...','#....','.#...','..#..','...#.')
g('=', '.....','.....','#####','.....','#####','.....','.....')
g('>', '.#...','..#..','...#.','....#','...#.','..#..','.#...')
g('?', '.###.','#...#','....#','...#.','..#..','.....','..#..')
g('_', '.....','.....','.....','.....','.....','.....','#####')
g('%', '##..#','##..#','...#.','..#..','.#...','#..##','#..##')
g('*', '.....','#.#.#','.###.','#####','.###.','#.#.#','.....')

g('0', '.###.','#...#','#..##','#.#.#','##..#','#...#','.###.')
g('1', '..#..','.##..','..#..','..#..','..#..','..#..','.###.')
g('2', '.###.','#...#','....#','...#.','..#..','.#...','#####')
g('3', '#####','...#.','..#..','...#.','....#','#...#','.###.')
g('4', '...#.','..##.','.#.#.','#..#.','#####','...#.','...#.')
g('5', '#####','#....','####.','....#','....#','#...#','.###.')
g('6', '..##.','.#...','#....','####.','#...#','#...#','.###.')
g('7', '#####','....#','...#.','..#..','.#...','.#...','.#...')
g('8', '.###.','#...#','#...#','.###.','#...#','#...#','.###.')
g('9', '.###.','#...#','#...#','.####','....#','...#.','.##..')

g('A', '.###.','#...#','#...#','#####','#...#','#...#','#...#')
g('B', '####.','#...#','#...#','####.','#...#','#...#','####.')
g('C', '.###.','#...#','#....','#....','#....','#...#','.###.')
g('D', '###..','#..#.','#...#','#...#','#...#','#..#.','###..')
g('E', '#####','#....','#....','####.','#....','#....','#####')
g('F', '#####','#....','#....','####.','#....','#....','#....')
g('G', '.###.','#...#','#....','#.###','#...#','#...#','.####')
g('H', '#...#','#...#','#...#','#####','#...#','#...#','#...#')
g('I', '.###.','..#..','..#..','..#..','..#..','..#..','.###.')
g('J', '..###','...#.','...#.','...#.','...#.','#..#.','.##..')
g('K', '#...#','#..#.','#.#..','##...','#.#..','#..#.','#...#')
g('L', '#....','#....','#....','#....','#....','#....','#####')
g('M', '#...#','##.##','#.#.#','#.#.#','#...#','#...#','#...#')
g('N', '#...#','#...#','##..#','#.#.#','#..##','#...#','#...#')
g('O', '.###.','#...#','#...#','#...#','#...#','#...#','.###.')
g('P', '####.','#...#','#...#','####.','#....','#....','#....')
g('Q', '.###.','#...#','#...#','#...#','#.#.#','#..#.','.##.#')
g('R', '####.','#...#','#...#','####.','#.#..','#..#.','#...#')
g('S', '.####','#....','#....','.###.','....#','....#','####.')
g('T', '#####','..#..','..#..','..#..','..#..','..#..','..#..')
g('U', '#...#','#...#','#...#','#...#','#...#','#...#','.###.')
g('V', '#...#','#...#','#...#','#...#','#...#','.#.#.','..#..')
g('W', '#...#','#...#','#...#','#.#.#','#.#.#','##.##','#...#')
g('X', '#...#','#...#','.#.#.','..#..','.#.#.','#...#','#...#')
g('Y', '#...#','#...#','.#.#.','..#..','..#..','..#..','..#..')
g('Z', '#####','....#','...#.','..#..','.#...','#....','#####')

# 0x01 / 0x02: solid selector triangles, left and right
g('\x01', '...#.','..##.','.###.','####.','.###.','..##.','...#.')
g('\x02', '.#...','.##..','.###.','.####','.###.','.##..','.#...')
# 0x03: a filled block, for meters and bars
g('\x03', '#####','#####','#####','#####','#####','#####','#####')
# 0x04: an empty box outline
g('\x04', '#####','#...#','#...#','#...#','#...#','#...#','#####')

def cols(rows):
    out = []
    for c in range(5):
        b = 0
        for r in range(7):
            if rows[r][c] == '#':
                b |= 1 << r
        out.append(b)
    return out

lines = []
lines.append('/*')
lines.append(' * ui_font.c - GENERATED by tools/mkfont.py, do not edit by hand.')
lines.append(' *')
lines.append(' * 5x7 glyphs, 5 column bytes each, bit 0 = top row. Indexed by')
lines.append(' * ASCII minus 0x20; codes 0x01-0x04 live at the end as UI symbols.')
lines.append(' */')
lines.append('#include "ui.h"')
lines.append('')
lines.append('const uint8_t se_ui_font[SE_FONT_GLYPHS][SE_FONT_W] = {')
missing = []
for code in range(0x20, 0x5F + 1):
    ch = chr(code)
    if ch in G:
        data = cols(G[ch])
    else:
        missing.append(ch)
        data = [0, 0, 0, 0, 0]
    lines.append('    { %s }, /* %s */' % (
        ', '.join('0x%02x' % b for b in data),
        ch if ch != ' ' else 'space'))
for i, ch in enumerate(['\x01', '\x02', '\x03', '\x04']):
    lines.append('    { %s }, /* symbol %d */' % (
        ', '.join('0x%02x' % b for b in cols(G[ch])), i + 1))
lines.append('};')
lines.append('')

open('engine/ui_font.c', 'w').write('\n'.join(lines))
print('wrote engine/ui_font.c: %d glyphs, %d blank' % (0x5F - 0x20 + 1 + 4, len(missing)))
if missing:
    print('  blank (unused):', ''.join(missing))
