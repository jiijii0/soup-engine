# Kodak Ektachrome E100: the clean, cool slide film.
#
# Kodachrome is warm and dense and a little eccentric about red. Ektachrome
# is the other school of slide film: neutral to slightly cool, bright clean
# whites, blues and cyans that are strong and clear, and greens that stay
# natural instead of going olive. The grain is very fine. It is the
# technical, accurate-looking slide.
#
# So here the colour is in the cool end of the palette: HUE_SAT lifts cyan
# and blue, greens are nudged toward cyan rather than yellow (the reverse
# of the Kodachrome file), and the curves hold a slight blue in the shadows
# and keep the highlights open. SAT is moderate, a little above Provia.
#
# Against KODACHROME: that is warm, dense and olive. This is cool, open and
# clear. They should not be mistakable side by side.
